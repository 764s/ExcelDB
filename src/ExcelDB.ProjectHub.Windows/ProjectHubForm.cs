    private async void InitialInspectAsync(object? sender, EventArgs eventArgs)
    {
        if (!string.IsNullOrWhiteSpace(_projectPath.Text) && Directory.Exists(_projectPath.Text))
            await InspectSelectedPathAsync(recordRecent: true);
    }

    private async void SelectProjectDirectoryAsync(object? sender, EventArgs eventArgs)
    {
        using var picker = new FolderBrowserDialog
        {
            Description = "选择空目录或已有 ExcelDB 项目目录",
            UseDescriptionForTitle = true,
            ShowNewFolderButton = true,
            SelectedPath = Directory.Exists(_projectPath.Text) ? _projectPath.Text : string.Empty,
        };
        if (picker.ShowDialog(this) != DialogResult.OK)
            return;
        _projectPath.Text = picker.SelectedPath;
        await InspectSelectedPathAsync(recordRecent: true);
    }

    private async Task InspectSelectedPathAsync(bool recordRecent)
    {
        if (string.IsNullOrWhiteSpace(_projectPath.Text))
        {
            MessageBox.Show(this, "请先选择项目目录。", "ExcelDB", MessageBoxButtons.OK, MessageBoxIcon.Information);
            return;
        }
        await RunBusyAsync(() => InspectCoreAsync(_projectPath.Text, recordRecent, showInspectionStatus: true));
    }

    private async Task InspectCoreAsync(string path, bool recordRecent, bool showInspectionStatus)
    {
        var location = ProjectLocation.From(path);
        var requestedProjectRoot = ResolveProjectRoot(location.Path);
        var previousProjectRoot = _inspection?.ProjectRoot;
        if (previousProjectRoot is not null
            && !string.Equals(previousProjectRoot, requestedProjectRoot, StringComparison.OrdinalIgnoreCase))
        {
            _inspection = null;
            _currentReportPath = null;
            UpdateReportAvailability();
        }

        var inspection = await Task.Run(() => _service.Inspect(location));
        if (inspection.ProjectFilePath is not null
            && inspection.Status is not (ProjectStatus.Uninitialized
                or ProjectStatus.Legacy
                or ProjectStatus.Invalid
                or ProjectStatus.RecoveryRequired))
        {
            var attributeReport = await Task.Run(() => _service.RepairProjectOwnedAttributes(location));
            if (!attributeReport.Diagnostics.IsEmpty)
            {
                inspection = inspection with
                {
                    Diagnostics = inspection.Diagnostics
                        .AddRange(attributeReport.Diagnostics)
                        .Distinct()
                        .ToImmutableArray(),
                };
            }
        }
        if (previousProjectRoot is not null
            && !string.Equals(previousProjectRoot, inspection.ProjectRoot, StringComparison.OrdinalIgnoreCase))
        {
            _currentReportPath = null;
        }
        _inspection = inspection;
        _projectPath.Text = inspection.ProjectRoot;
        ApplyInspection(inspection);
        string? recentWarning = null;
        if (recordRecent)
        {
            try
            {
                _stateStore.RecordOpened(inspection.ProjectRoot);
                LoadRecentProjects();
            }
            catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
            {
                recentWarning = $"最近项目记录未保存：{exception.Message}";
            }
        }
        if (showInspectionStatus)
        {
            var diagnostic = inspection.Diagnostics.FirstOrDefault(static item => item.IsFailure)
                ?? inspection.Diagnostics.FirstOrDefault();
            _status.Text = diagnostic is null
                ? $"项目状态：{inspection.Status}"
                : $"项目状态：{inspection.Status} — {diagnostic.Message}";
            if (recentWarning is not null)
                _status.Text += $"；{recentWarning}";
        }
    }

    private void ApplyInspection(ProjectInspection inspection, bool updateReportPath = true)
    {
        _schemaCard.UpdateInspection(inspection.Schema);
        _excelCard.UpdateInspection(inspection.Excel);
        _generatedCSharpCard.UpdateInspection(inspection.GeneratedCSharp);
        _generatedBytesCard.UpdateInspection(inspection.GeneratedBytes);

        SetAvailability(_initialize, inspection.Actions.Initialize);
        SetAvailability(_createTable, inspection.Actions.CreateTable);
        SetAvailability(_editTable, inspection.Actions.EditTable);
        SetAvailability(_regenerate, inspection.Actions.Regenerate);
        SetAvailability(_prepareRows, inspection.Actions.PrepareRows);
        SetAvailability(_check, inspection.Actions.Check);
        SetAvailability(_convert, inspection.Actions.Convert);
        SetAvailability(_repairImports, inspection.Actions.RepairSystemImports);
        SetAvailability(_configure, inspection.Actions.Configure);

        if (updateReportPath)
            _currentReportPath = ExistingPath(inspection.LatestReportPath);
        UpdateReportAvailability();
        _openConfiguration.Enabled = !_busy && ExistingPath(inspection.ProjectFilePath) is not null;
        _openInternal.Enabled = !_busy && ExistingPath(inspection.InternalDirectory) is not null;
        _openRecovery.Enabled = !_busy && ExistingPath(inspection.RecoveryDirectory) is not null;
        _cleanCache.Enabled = !_busy && inspection.InternalDirectory is not null;

        var disabled = new[]
        {
            ("初始化", inspection.Actions.Initialize),
            ("创建表", inspection.Actions.CreateTable),
            ("编辑表", inspection.Actions.EditTable),
            ("重新生成", inspection.Actions.Regenerate),
            ("准备行", inspection.Actions.PrepareRows),
            ("检查", inspection.Actions.Check),
            ("生成 bytes", inspection.Actions.Convert),
            ("修复 Proto", inspection.Actions.RepairSystemImports),
            ("设置", inspection.Actions.Configure),
        }.Where(static item => !item.Item2.Enabled && !string.IsNullOrWhiteSpace(item.Item2.DisabledReason))
            .Select(static item => $"{item.Item1}：{item.Item2.DisabledReason}")
            .Distinct(StringComparer.Ordinal)
            .ToArray();
        _availabilitySummary.Text = disabled.Length == 0 ? string.Empty : string.Join("  |  ", disabled);
    }

    private void SetAvailability(Button button, ProjectActionAvailability availability)
    {
        button.Enabled = !_busy && availability.Enabled;
        var reason = availability.Enabled ? string.Empty : availability.DisabledReason ?? "当前项目状态不允许此操作。";
        button.AccessibleDescription = reason;
        _toolTip.SetToolTip(button, reason);
    }

    private async Task InitializeProjectAsync()
    {
        var projectRoot = _inspection?.ProjectRoot ?? _projectPath.Text;
        using var dialog = new InitializeProjectDialog(projectRoot);
        if (dialog.ShowDialog(this) != DialogResult.OK)
            return;
        await ExecutePlanAsync(() => Task.Run(() => _service.PlanInitialize(new InitializeProjectRequest(
            ProjectLocation.From(dialog.ProjectRoot),
            dialog.GeneratedCSharpDirectory))));
    }

    private async Task CreateTableAsync()
    {
        if (_inspection is null)
            return;
        var defaultWorkbook = ProjectArtifactPaths.GetDefaultWorkbookPath(
            _inspection.ProjectRoot,
            _inspection.Excel.Path);
        using var dialog = new CreateTableDialog(defaultWorkbook);
        if (dialog.ShowDialog(this) != DialogResult.OK)
            return;
        var request = new CreateTableRequest(ProjectLocation.From(_inspection.ProjectRoot), dialog.CreateIntent());
        await ExecutePlanAsync(() => _service.PlanCreateTableAsync(request));
    }

    private async Task EditTableAsync()
    {
        if (_inspection is null)
            return;
        using var dialog = new EditTableDialog();
        if (dialog.ShowDialog(this) != DialogResult.OK)
            return;
        var request = new EditTableRequest(ProjectLocation.From(_inspection.ProjectRoot), dialog.CreateIntent());
        await ExecutePlanAsync(() => _service.PlanEditTableAsync(request));
    }

    private async Task RegenerateAsync()
    {
        if (_inspection is null)
            return;
        var request = new RegenerateRequest(ProjectLocation.From(_inspection.ProjectRoot));
        await ExecutePlanAsync(() => _service.PlanRegenerateAsync(request));
    }

    private async Task PrepareRowsAsync()
    {
        if (_inspection is null)
            return;
        var request = new DataPrepareRequest(ProjectLocation.From(_inspection.ProjectRoot));
        await ExecutePlanAsync(() => _service.PlanDataPrepareAsync(request));
    }

    private async Task CheckAsync()
    {
        if (_inspection is null)
            return;
        await ExecuteReportOperationAsync(() => _service.CheckAsync(new CheckRequest(ProjectLocation.From(_inspection.ProjectRoot))));
    }

    private async Task ConvertAsync()
    {
        if (_inspection is null)
            return;
        using var dialog = new TargetDialog();
        if (dialog.ShowDialog(this) != DialogResult.OK)
            return;
        var request = new ConvertRequest(ProjectLocation.From(_inspection.ProjectRoot), dialog.Target);
        await ExecuteReportOperationAsync(() => _service.ConvertAsync(request));
    }

    private async Task RepairImportsAsync()
    {
        if (_inspection is null)
            return;
        var request = new RepairSystemImportsRequest(ProjectLocation.From(_inspection.ProjectRoot));
        await ExecutePlanAsync(() => Task.Run(() => _service.PlanRepairSystemImports(request)));
    }

    private async Task ConfigureProjectAsync()
    {
        if (_inspection is null)
            return;
        using var dialog = new ProjectSettingsDialog(_inspection);
        if (dialog.ShowDialog(this) != DialogResult.OK)
            return;
        var request = new ConfigureProjectRequest(
            ProjectLocation.From(_inspection.ProjectRoot),
            dialog.SchemaDirectory,
            dialog.ExcelDirectory,
            dialog.GeneratedCSharpDirectory,
            dialog.GeneratedBytesDirectory);
        await ExecutePlanAsync(() => Task.Run(() => _service.PlanConfigure(request)));
    }

    private async Task CleanCacheAsync()
    {
        if (_inspection is null)
            return;
        if (MessageBox.Show(
                this,
                "只清理可删除的 .exceldb/cache；配置、发布历史、报告和恢复日志不会被删除。继续吗？",
                "清理 ExcelDB 缓存",
                MessageBoxButtons.OKCancel,
                MessageBoxIcon.Question) != DialogResult.OK)
        {
            return;
        }
        var location = ProjectLocation.From(_inspection.ProjectRoot);
        await ExecuteReportOperationAsync(() => Task.Run(() => _service.CleanCache(location)));
    }

    private async Task ExecutePlanAsync(Func<Task<MutationPlan>> createPlan)
    {
        await RunBusyAsync(async () =>
        {
            _status.Text = "正在构造不可变操作计划…";
            var plan = await createPlan();
            if (!PlanPreviewDialog.Confirm(this, plan))
            {
                _status.Text = "已取消；项目工件没有写入。";
                return;
            }
            _status.Text = "正在应用已确认的计划…";
            var report = await Task.Run(() => _service.Apply(plan));
            await RefreshAfterReportAsync(report);
        });
    }

    private async Task ExecuteReportOperationAsync(Func<Task<OperationReport>> operation)
    {
        await RunBusyAsync(async () =>
        {
            _status.Text = "正在执行…";
            var report = await operation();
            await RefreshAfterReportAsync(report);
        });
    }

    private async Task RefreshAfterReportAsync(OperationReport report)
    {
        var reportArtifact = report.Artifacts.FirstOrDefault(static item =>
            item.Kind.Contains("report", StringComparison.OrdinalIgnoreCase));
        var operationReportPath = reportArtifact is null ? null : ExistingPath(reportArtifact.Path);
        _currentReportPath = operationReportPath;
        UpdateReportAvailability();

        if (_inspection is not null)
        {
            try
            {
                await InspectCoreAsync(_inspection.ProjectRoot, recordRecent: false, showInspectionStatus: false);
            }
            catch (Exception exception)
            {
                PresentException("操作完成，但刷新项目状态失败", exception);
                return;
            }
        }

        _currentReportPath = operationReportPath ?? ExistingPath(_inspection?.LatestReportPath);
        var diagnostic = report.Diagnostics.FirstOrDefault(static item => item.IsFailure)
            ?? report.Diagnostics.FirstOrDefault();
        _status.Text = report.Succeeded
            ? report.Applied ? $"{report.Operation} 已应用。" : $"{report.Operation} 已完成，无需修改领域工件。"
            : $"{report.Operation} 失败；{diagnostic?.Message ?? "原有领域工件已保留。"}";
        UpdateReportAvailability();
    }

    private async Task RunBusyAsync(Func<Task> action)
    {
        if (_busy)
            return;
        SetBusy(true);
        try
        {
            await action();
        }
        catch (Exception exception)
        {
            PresentException("ExcelDB 操作失败", exception);
        }
        finally
        {
            SetBusy(false);
        }
    }

    private void SetBusy(bool busy)
    {
        _busy = busy;
        UseWaitCursor = busy;
        _projectPath.Enabled = !busy;
        _selectProject.Enabled = !busy;
        _inspectProject.Enabled = !busy;
        _recentProjects.Enabled = !busy;
        _clearRecent.Enabled = !busy;
        _removeRecent.Enabled = !busy && _recentProjects.SelectedItem is RecentProjectItem;
        if (_inspection is null)
        {
            foreach (var button in _operationButtons.Concat(_advancedButtons))
                button.Enabled = false;
        }
        else
        {
            ApplyInspection(_inspection, updateReportPath: false);
        }
    }

    private void PresentException(string heading, Exception exception)
    {
        _status.Text = $"{heading}：{exception.Message}";
        if (_currentReportPath is null && _inspection?.LatestReportPath is { } latest)
            _currentReportPath = ExistingPath(latest);
        UpdateReportAvailability();
        MessageBox.Show(this, exception.Message, heading, MessageBoxButtons.OK, MessageBoxIcon.Error);
    }

    private void UpdateReportAvailability()
    {
        _reportLink.Visible = _currentReportPath is not null;
        _openReport.Enabled = !_busy && _currentReportPath is not null;
    }

    private void OpenPath(string? path, string title)
    {
        if (string.IsNullOrWhiteSpace(path))
        {
            MessageBox.Show(this, "当前没有可打开的路径。", title, MessageBoxButtons.OK, MessageBoxIcon.Information);
            return;
        }
        try
        {
            _shell.Open(path);
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException or InvalidOperationException)
        {
            MessageBox.Show(this, exception.Message, title, MessageBoxButtons.OK, MessageBoxIcon.Warning);
        }
    }

    private void LoadRecentProjects()
    {
        var selectedPath = (_recentProjects.SelectedItem as RecentProjectItem)?.Project.Path;
        _recentProjects.BeginUpdate();
        try
        {
            _recentProjects.Items.Clear();
            foreach (var project in _stateStore.Load().RecentProjects)
                _recentProjects.Items.Add(new RecentProjectItem(project, Directory.Exists(project.Path)));
            if (selectedPath is not null)
            {
                var selected = _recentProjects.Items.Cast<RecentProjectItem>()
                    .FirstOrDefault(item => string.Equals(item.Project.Path, selectedPath, StringComparison.OrdinalIgnoreCase));
                if (selected is not null)
                    _recentProjects.SelectedItem = selected;
            }
        }
        finally
        {
            _recentProjects.EndUpdate();
        }
        _clearRecent.Enabled = !_busy && _recentProjects.Items.Count != 0;
    }

    private async void RecentProjectDoubleClickAsync(object? sender, EventArgs eventArgs)
    {
        if (_recentProjects.SelectedItem is not RecentProjectItem item)
            return;
        if (!item.Exists)
        {
            MessageBox.Show(this, "该最近项目目录已经不存在；可选择“移除所选”。", "最近项目", MessageBoxButtons.OK, MessageBoxIcon.Information);
            return;
        }
        _projectPath.Text = item.Project.Path;
        await InspectSelectedPathAsync(recordRecent: true);
    }

    private void RemoveRecentProject(object? sender, EventArgs eventArgs)
    {
        if (_recentProjects.SelectedItem is not RecentProjectItem item)
            return;
        try
        {
            _stateStore.Remove(item.Project.Path);
            LoadRecentProjects();
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            PresentException("无法移除最近项目", exception);
        }
    }

    private void ClearRecentProjects(object? sender, EventArgs eventArgs)
    {
        if (_recentProjects.Items.Count == 0)
            return;
        if (MessageBox.Show(this, "清空最近项目导航记录？这不会修改任何项目。", "最近项目", MessageBoxButtons.OKCancel, MessageBoxIcon.Question) != DialogResult.OK)
            return;
        try
        {
            _stateStore.Clear();
            LoadRecentProjects();
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
        {
            PresentException("无法清空最近项目", exception);
        }
    }

    private static string? ExistingPath(string? path) =>
        !string.IsNullOrWhiteSpace(path) && (File.Exists(path) || Directory.Exists(path)) ? path : null;

    private static string ResolveProjectRoot(string path)
    {
        var full = Path.GetFullPath(path);
        if (string.Equals(Path.GetFileName(full), "project.json", StringComparison.OrdinalIgnoreCase)
            && string.Equals(Path.GetFileName(Path.GetDirectoryName(full)), ".exceldb", StringComparison.OrdinalIgnoreCase))
        {
            return Path.GetDirectoryName(Path.GetDirectoryName(full)!)!;
        }
        return File.Exists(full)
            ? Path.GetDirectoryName(full) ?? full
            : full;
    }

    private sealed record RecentProjectItem(RecentProject Project, bool Exists)
    {
        public override string ToString()
        {
            var name = Path.GetFileName(Project.Path);
            if (string.IsNullOrWhiteSpace(name))
                name = Project.Path;
            return $"{(Exists ? string.Empty : "[不存在] ")}{name} — {Project.Path}";
        }
    }
