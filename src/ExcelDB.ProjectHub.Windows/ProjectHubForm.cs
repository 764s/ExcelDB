    public ProjectHubForm(
        IExcelDbProjectService service,
        string initialDirectory,
        LauncherStateStore? stateStore = null,
        IProjectHubShell? shell = null)
    {
        _service = service ?? throw new ArgumentNullException(nameof(service));
        ArgumentNullException.ThrowIfNull(initialDirectory);
        _stateStore = stateStore ?? new LauncherStateStore();
        _shell = shell ?? new WindowsProjectHubShell();

        Text = "ExcelDB Project Hub";
        StartPosition = FormStartPosition.CenterScreen;
        MinimumSize = new Size(900, 720);
        Size = new Size(1060, 850);
        AutoScaleMode = AutoScaleMode.Dpi;

        _schemaCard = new ArtifactCardControl("Schema");
        _excelCard = new ArtifactCardControl("Excel");
        _generatedCSharpCard = new ArtifactCardControl("Generated C#");
        _generatedBytesCard = new ArtifactCardControl("Generated Bytes");
        foreach (var card in ArtifactCards)
            card.OpenRequested += (_, _) => OpenPath(card.ArtifactPath, $"打开 {card.ArtifactName}");

        Controls.Add(BuildLayout());
        LoadRecentProjects();

        if (!string.IsNullOrWhiteSpace(initialDirectory))
        {
            try
            {
                _projectPath.Text = Path.GetFullPath(initialDirectory);
            }
            catch (Exception exception) when (exception is ArgumentException or NotSupportedException or PathTooLongException)
            {
                _status.Text = $"初始目录无效：{exception.Message}";
            }
        }

        Shown += InitialInspectAsync;
    }

