    private static void AppendEnum(
        StringBuilder builder,
        CanonicalEnumDescriptor descriptor,
        string typeName)
    {
        builder.Append("public enum ").Append(typeName).AppendLine();
        builder.AppendLine("{");
        var used = new HashSet<string>(StringComparer.Ordinal);
        foreach (var value in descriptor.Values)
        {
            var name = UniqueIdentifier(ToPascalIdentifier(value.Name), value.Number, used);
            builder.Append("    ").Append(name).Append(" = ")
                .Append(value.Number.ToString(CultureInfo.InvariantCulture)).AppendLine(",");
        }

        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void AppendPoco(
        StringBuilder builder,
        ShapeDefinition definition,
        string typeName,
        IReadOnlyDictionary<string, string> typeNames,
        string? target)
    {
        if (definition.TableId is { } tableId)
        {
            builder.Append("[GeneratedTable(")
                .Append(tableId.ToString(CultureInfo.InvariantCulture)).Append(", ")
                .Append(CSharpString(definition.FullName)).AppendLine(")] ");
        }

        builder.Append("public sealed partial class ").Append(typeName).AppendLine();
        builder.AppendLine("{");
        var fields = definition.Fields.Values
            .Where(field => target is null || field.ExportTargets.Contains(target, StringComparer.Ordinal))
            .OrderBy(static field => field.Id)
            .ToArray();
        var memberNames = BuildMemberNames(fields);
        foreach (var group in fields
                     .Where(static field => field.OneOfGroup is not null)
                     .GroupBy(static field => field.OneOfGroup!, StringComparer.Ordinal)
                     .OrderBy(static group => group.Key, StringComparer.Ordinal))
        {
            builder.Append("    public int ")
                .Append(ToPascalIdentifier(group.Key)).AppendLine("VariantId { get; set; }");
        }

        foreach (var field in fields)
        {
            var memberName = memberNames[field.Id];
            builder.Append("    [GeneratedField(")
                .Append(field.Id.ToString(CultureInfo.InvariantCulture)).Append(", ")
                .Append(CSharpString(FormatFieldIdPath(field))).Append(", ")
                .Append(CSharpString(field.PropertyPath)).AppendLine(")] ");
            builder.Append("    public ").Append(GetCSharpType(field, typeNames))
                .Append(' ').Append(memberName).Append(" { get; set; }")
                .Append(GetInitializer(field, typeNames)).AppendLine();
        }

        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void AppendSurfaceBindings(
        StringBuilder builder,
        CanonicalSchemaDescriptor descriptor,
        string? target,
        IReadOnlyDictionary<string, string> typeNames)
    {
        var tables = descriptor.Tables
            .Where(table => target is null || table.ExportTargets.Contains(target, StringComparer.Ordinal))
            .OrderBy(static table => table.Id)
            .ThenBy(static table => table.FullName, StringComparer.Ordinal)
            .ToArray();
        builder.AppendLine("public static class GeneratedSchemaBindings");
        builder.AppendLine("{");
        builder.AppendLine("    public static IReadOnlyList<GeneratedTableBinding> Tables { get; } = Array.AsReadOnly(new GeneratedTableBinding[]");
        builder.AppendLine("    {");
        foreach (var table in tables)
        {
            var fields = Flatten(table.Fields)
                .Where(field => target is null || field.ExportTargets.Contains(target, StringComparer.Ordinal))
                .OrderBy(static field => field.PropertyPath, StringComparer.Ordinal)
                .ThenBy(static field => field.Id)
                .ToArray();
            var topLevelMembers = BuildMemberNames(table.Fields);
            builder.Append("        new(")
                .Append(table.Id.ToString(CultureInfo.InvariantCulture)).Append(", ")
                .Append(CSharpString(table.FullName)).Append(", ")
                .Append(CSharpNullableString(table.DisplayName)).Append(", typeof(")
                .Append(typeNames[table.FullName]).Append("), ")
                .Append(CSharpString($"factory:{table.Id}")).Append(", ")
                .Append(CSharpString($"accessor:{table.Id}")).Append(", ")
                .Append(CSharpString($"patcher:{table.Id}")).AppendLine(", Array.AsReadOnly(new GeneratedFieldBinding[]");
            builder.AppendLine("        {");
            foreach (var field in fields)
            {
                var member = BuildMemberPath(field.PropertyPath, table.Fields, topLevelMembers);
                var codecName = CodecMethodName(table.Id, table.FullName, field);
                var fieldType = GetCSharpType(field, typeNames);
                var child = field.ChildTable;
                builder.Append("            new(")
                    .Append(field.Id.ToString(CultureInfo.InvariantCulture)).Append(", ")
                    .Append(IntArrayExpression(field.FieldIdPath)).Append(", ")
                    .Append(CSharpString(field.PropertyPath)).Append(", ")
                    .Append(CSharpString(member)).Append(", ")
                    .Append(CSharpNullableString(field.DisplayName)).Append(", ")
                    .Append(CSharpNullableString(field.HeaderComment)).Append(", ")
                    .Append(StringArrayExpression(field.Aliases)).Append(", ")
                    .Append(PhysicalKindExpression(field)).Append(", ")
                    .Append(CSharpNullableString(child?.SheetName)).Append(", ")
                    .Append(CSharpNullableString(child?.ParentGuidColumn)).Append(", ")
                    .Append(CSharpNullableString(child?.OrdinalColumn)).Append(", ")
                    .Append(CSharpNullableString(child?.MapKeyColumn)).Append(", ")
                    .Append("static text => GeneratedAuthoringCellCodecs.").Append(codecName)
                    .Append("_Parse(text), static value => GeneratedAuthoringCellCodecs.").Append(codecName)
                    .Append("_Write((").Append(fieldType).Append(")value!), ")
                    .Append(CSharpString($"accessor:{table.Id}:{field.PropertyPath}")).Append(", ")
                    .Append(CSharpString($"patcher:{table.Id}:{field.PropertyPath}")).AppendLine("),");
            }

            builder.AppendLine("        })),");
        }

        builder.AppendLine("    });");
        builder.AppendLine("}");
        builder.AppendLine();
        builder.AppendLine("public static class GeneratedAuthoringCellCodecs");
        builder.AppendLine("{");
        foreach (var table in tables)
        {
            foreach (var field in Flatten(table.Fields)
                         .OrderBy(static field => string.Join(".", field.FieldIdPath), StringComparer.Ordinal))
            {
                var codecName = CodecMethodName(table.Id, table.FullName, field);
                var fieldType = GetCSharpType(field, typeNames);
                builder.Append("    public static ").Append(fieldType).Append(' ').Append(codecName)
                    .Append("_Parse(string text) => GeneratedCanonicalCellCodec.Parse<")
                    .Append(fieldType).AppendLine(">(text);");
                builder.Append("    public static string ").Append(codecName).Append("_Write(")
                    .Append(fieldType).Append(" value) => GeneratedCanonicalCellCodec.Write(value);")
                    .AppendLine();
            }
        }
        builder.AppendLine("}");
    }

    private static void AppendRuntimeBindings(
        StringBuilder builder,
        CanonicalSchemaDescriptor descriptor,
        string target,
        IReadOnlyDictionary<string, string> typeNames)
    {
        var tables = descriptor.Tables
            .Where(table => table.Kind == CanonicalTableKind.Asset
                && table.ExportTargets.Contains(target, StringComparer.Ordinal))
            .OrderBy(static table => table.Id)
            .ToArray();

        builder.AppendLine("internal static class RuntimeGeneratedValueCodec");
        builder.AppendLine("{");
        builder.AppendLine("    private static readonly JsonSerializerOptions JsonOptions = new JsonSerializerOptions { PropertyNameCaseInsensitive = true, PropertyNamingPolicy = JsonNamingPolicy.SnakeCaseLower };");
        builder.AppendLine("    public static T Parse<T>(ReadOnlySpan<byte> data)");
        builder.AppendLine("    {");
        builder.AppendLine("        var declared = typeof(T);");
        builder.AppendLine("        var type = Nullable.GetUnderlyingType(declared) ?? declared;");
        builder.AppendLine("        if (data.IsEmpty && Nullable.GetUnderlyingType(declared) is not null) return default!;");
        builder.AppendLine("        if (type == typeof(byte[])) return (T)(object)data.ToArray();");
        builder.AppendLine("        var text = Encoding.UTF8.GetString(data);");
        builder.AppendLine("        object value;");
        builder.AppendLine("        if (type == typeof(string)) value = text;");
        builder.AppendLine("        else if (type == typeof(bool)) value = bool.Parse(text);");
        builder.AppendLine("        else if (type == typeof(int)) value = int.Parse(text, NumberStyles.Integer, CultureInfo.InvariantCulture);");
        builder.AppendLine("        else if (type == typeof(uint)) value = uint.Parse(text, NumberStyles.Integer, CultureInfo.InvariantCulture);");
        builder.AppendLine("        else if (type == typeof(long)) value = long.Parse(text, NumberStyles.Integer, CultureInfo.InvariantCulture);");
        builder.AppendLine("        else if (type == typeof(ulong)) value = ulong.Parse(text, NumberStyles.Integer, CultureInfo.InvariantCulture);");
        builder.AppendLine("        else if (type == typeof(float)) value = float.Parse(text, NumberStyles.Float, CultureInfo.InvariantCulture);");
        builder.AppendLine("        else if (type == typeof(double)) value = double.Parse(text, NumberStyles.Float, CultureInfo.InvariantCulture);");
        builder.AppendLine("        else if (type == typeof(RowRef))");
        builder.AppendLine("        {");
        builder.AppendLine("            if (!AssetIdentity.TryParse(text, out var identity)) throw new FormatException($\"Invalid RowRef '{text}'.\");");
        builder.AppendLine("            value = new RowRef(identity);");
        builder.AppendLine("        }");
        builder.AppendLine("        else if (type.IsEnum) value = int.TryParse(text, NumberStyles.Integer, CultureInfo.InvariantCulture, out var number) ? Enum.ToObject(type, number) : Enum.Parse(type, text, ignoreCase: false);");
        builder.AppendLine("        else return JsonSerializer.Deserialize<T>(data, JsonOptions)!;");
        builder.AppendLine("        return (T)value;");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        builder.AppendLine();

        builder.AppendLine("internal static class GeneratedRuntimeBindings");
        builder.AppendLine("{");
        builder.AppendLine("    public static IReadOnlyList<RuntimeTableBinding> Tables { get; } = Array.AsReadOnly(new RuntimeTableBinding[]");
        builder.AppendLine("    {");
        foreach (var table in tables)
        {
            var typeName = typeNames[table.FullName];
            builder.Append("        new RuntimeTableBinding<").Append(typeName).Append(">(")
                .Append(table.Id.ToString(CultureInfo.InvariantCulture)).Append(", static () => new ")
                .Append(typeName).Append("(), Apply_").Append(table.Id)
                .Append(", Reset_").Append(table.Id)
                .Append(", CreateRollback_").Append(table.Id)
                .Append(", CaptureRollback_").Append(table.Id)
                .Append(", Restore_").Append(table.Id).AppendLine("),");
        }

        builder.AppendLine("    });");
        builder.AppendLine();
        foreach (var table in tables)
        {
            var typeName = typeNames[table.FullName];
            var fields = table.Fields
                .Where(field => field.ExportTargets.Contains(target, StringComparer.Ordinal))
                .OrderBy(static field => field.Id)
                .ToArray();
            var runtimeFields = Flatten(table.Fields)
                .Where(field => field.ExportTargets.Contains(target, StringComparer.Ordinal))
                .OrderBy(static field => string.Join(".", field.FieldIdPath), StringComparer.Ordinal)
                .ToArray();
            var members = BuildMemberNames(table.Fields);
            builder.Append("    private static void Apply_").Append(table.Id).Append('(')
                .Append(typeName).AppendLine(" instance, RuntimeAssetRecord record)");
            builder.AppendLine("    {");
            builder.Append("        Reset_").Append(table.Id).AppendLine("(instance);");
            builder.AppendLine("        foreach (var field in record.Fields)");
            builder.AppendLine("        {");
            foreach (var field in runtimeFields)
                AppendRuntimeFieldAssignment(builder, table, field, typeNames);
            builder.AppendLine("        }");
            builder.AppendLine("    }");

            builder.Append("    private static void Reset_").Append(table.Id).Append('(')
                .Append(typeName).AppendLine(" instance)");
            builder.AppendLine("    {");
            foreach (var field in fields)
            {
                builder.Append("        instance.").Append(members[field.Id]).Append(" = ")
                    .Append(GetResetExpression(field)).AppendLine(";");
            }

            builder.AppendLine("    }");
            builder.Append("    private sealed class RollbackState_").Append(table.Id).AppendLine();
            builder.AppendLine("    {");
            for (var index = 0; index < fields.Length; index++)
            {
                builder.Append("        public ").Append(GetCSharpType(fields[index], typeNames))
                    .Append(" Value_").Append(index.ToString(CultureInfo.InvariantCulture))
                    .AppendLine(" = default!;");
            }

            builder.AppendLine("    }");
            builder.Append("    private static object CreateRollback_").Append(table.Id).Append('(')
                .Append(typeName).Append(" _) => new RollbackState_").Append(table.Id).AppendLine("();");
            builder.Append("    private static void CaptureRollback_").Append(table.Id).Append('(')
                .Append(typeName).AppendLine(" instance, object state)");
            builder.AppendLine("    {");
            builder.Append("        var values = (RollbackState_").Append(table.Id).AppendLine(")state;");
            for (var index = 0; index < fields.Length; index++)
            {
                var field = fields[index];
                builder.Append("        values.Value_").Append(index.ToString(CultureInfo.InvariantCulture))
                    .Append(" = instance.").Append(members[field.Id]).AppendLine(";");
            }

            builder.AppendLine("    }");
            builder.Append("    private static void Restore_").Append(table.Id).Append('(')
                .Append(typeName).AppendLine(" instance, object state)");
            builder.AppendLine("    {");
            builder.Append("        var values = (RollbackState_").Append(table.Id).AppendLine(")state;");
            for (var index = 0; index < fields.Length; index++)
            {
                var field = fields[index];
                builder.Append("        instance.").Append(members[field.Id]).Append(" = values.Value_")
                    .Append(index.ToString(CultureInfo.InvariantCulture)).AppendLine(";");
            }

            builder.AppendLine("    }");
            builder.AppendLine();
        }

        builder.AppendLine("}");
    }

    private static string GetResetExpression(CanonicalFieldDescriptor field)
    {
        if (field.HasPresence)
            return "default!";
        if (field.Map is not null
            || field.Shape is CanonicalFieldShape.RepeatedScalar
                or CanonicalFieldShape.RepeatedEnum
                or CanonicalFieldShape.RepeatedMessage)
        {
            return "new()";
        }

        return field.TypeName switch
        {
            "string" => "string.Empty",
            "bytes" => "Array.Empty<byte>()",
            _ => "default!",
        };
    }

    private static string GenerateRegistry(
        CanonicalSchemaDescriptor descriptor,
        string target,
        string safeTarget,
        IReadOnlyDictionary<string, string> typeNames)
    {
        var builder = new StringBuilder();
        var namespaceName = $"ExcelDb.Generated.Runtime.{safeTarget}";
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using ExcelDb.Core.Identity;");
        builder.AppendLine();
        builder.Append("namespace ").Append(namespaceName).AppendLine();
        builder.AppendLine("{");
        builder.AppendLine();
        builder.AppendLine("public sealed class RuntimeSchemaRegistry : global::ExcelDb.Runtime.RuntimeSchemaRegistry");
        builder.AppendLine("{");
        builder.AppendLine("    public static RuntimeSchemaRegistry Instance { get; } = new RuntimeSchemaRegistry();");
        builder.Append("    private RuntimeSchemaRegistry() : base(0x")
            .Append(descriptor.SchemaHash.ToString("x16", CultureInfo.InvariantCulture))
            .Append("UL, new ExportTargetId(").Append(CSharpString(target))
            .AppendLine("), GeneratedRuntimeBindings.Tables) { }");
        builder.AppendLine("}");
        builder.AppendLine("}");
        _ = typeNames;
        return NormalizeNewLines(builder.ToString());
    }

    private static void AppendRuntimeFieldAssignment(
        StringBuilder builder,
        CanonicalTableDescriptor table,
        CanonicalFieldDescriptor field,
        IReadOnlyDictionary<string, string> typeNames)
    {
        var chain = ResolveFieldChain(table, field);
        var path = field.FieldIdPath.IsDefaultOrEmpty ? [field.Id] : field.FieldIdPath;
        builder.Append("            if (field.FieldIdPath.Length == ")
            .Append(path.Length.ToString(CultureInfo.InvariantCulture));
        for (var index = 0; index < path.Length; index++)
        {
            builder.Append(" && field.FieldIdPath[")
                .Append(index.ToString(CultureInfo.InvariantCulture))
                .Append("] == ")
                .Append(path[index].ToString(CultureInfo.InvariantCulture));
        }
        builder.AppendLine(")");
        builder.AppendLine("            {");

        var access = "instance";
        var siblings = table.Fields;
        for (var index = 0; index < chain.Length; index++)
        {
            var descriptor = chain[index];
            var member = BuildMemberNames(siblings)[descriptor.Id];
            access += "." + member;
            if (index < chain.Length - 1)
            {
                builder.Append("                if (").Append(access).Append(" is null) ")
                    .Append(access).Append(" = new ")
                    .Append(ResolveType(descriptor.TypeName, typeNames)).AppendLine("();");
            }
            siblings = descriptor.Children;
        }

        builder.Append("                ").Append(access)
            .Append(" = RuntimeGeneratedValueCodec.Parse<")
            .Append(GetCSharpType(field, typeNames)).AppendLine(">(field.Data.Span);");
        builder.AppendLine("                continue;");
        builder.AppendLine("            }");
    }

    private static ImmutableArray<CanonicalFieldDescriptor> ResolveFieldChain(
        CanonicalTableDescriptor table,
        CanonicalFieldDescriptor leaf)
    {
        var path = leaf.FieldIdPath.IsDefaultOrEmpty ? [leaf.Id] : leaf.FieldIdPath;
        var result = ImmutableArray.CreateBuilder<CanonicalFieldDescriptor>(path.Length);
        var siblings = table.Fields;
        foreach (var fieldId in path)
        {
            var descriptor = siblings.FirstOrDefault(candidate => candidate.Id == fieldId)
                ?? throw new InvalidOperationException(
                    $"Field path '{string.Join('.', path)}' is not rooted in table '{table.FullName}'.");
            result.Add(descriptor);
            siblings = descriptor.Children;
        }
        return result.ToImmutable();
    }

    private static Dictionary<string, ShapeDefinition> CollectDefinitions(
        CanonicalSchemaDescriptor descriptor,
        string? target)
    {
        var result = new Dictionary<string, ShapeDefinition>(StringComparer.Ordinal);
        foreach (var table in descriptor.Tables
                     .Where(table => target is null || table.ExportTargets.Contains(target, StringComparer.Ordinal)))
        {
            AddDefinition(result, table.FullName, table.Id, table.Fields, target);
        }

        return result;
    }

    private static void AddDefinition(
        Dictionary<string, ShapeDefinition> result,
        string fullName,
        int? tableId,
        IEnumerable<CanonicalFieldDescriptor> fields,
        string? target)
    {
        if (!result.TryGetValue(fullName, out var definition))
        {
            definition = new ShapeDefinition(fullName, tableId);
            result.Add(fullName, definition);
        }

        foreach (var field in fields.OrderBy(static item => item.Id))
        {
            if (target is not null && !field.ExportTargets.Contains(target, StringComparer.Ordinal))
                continue;
            definition.Fields.TryAdd(field.Id, field);

            var messageType = field.Map?.ValueShape == CanonicalFieldShape.Message
                ? field.Map.ValueTypeName
                : field.Shape is CanonicalFieldShape.Message
                    or CanonicalFieldShape.RepeatedMessage
                    or CanonicalFieldShape.OneOfVariant
                    ? field.TypeName
                    : null;
            if (messageType is null || IsBuiltInType(messageType) || field.Children.IsEmpty)
                continue;
            AddDefinition(result, messageType, null, field.Children, target);
        }
    }

    private static IReadOnlyDictionary<string, string> BuildTypeNames(
        CanonicalSchemaDescriptor descriptor,
        IEnumerable<string> messageNames)
    {
        var fullNames = messageNames.Concat(descriptor.Enums.Select(static item => item.FullName))
            .Distinct(StringComparer.Ordinal)
            .OrderBy(static value => value, StringComparer.Ordinal)
            .ToArray();
        var candidates = fullNames.ToDictionary(
            static fullName => fullName,
            static fullName => ToPascalIdentifier(fullName[(fullName.LastIndexOf('.') + 1)..]),
            StringComparer.Ordinal);
        var duplicateCandidates = candidates.Values
            .GroupBy(static value => value, StringComparer.Ordinal)
            .Where(static group => group.Count() > 1)
            .Select(static group => group.Key)
            .ToHashSet(StringComparer.Ordinal);
        return candidates.ToDictionary(
            static pair => pair.Key,
            pair => duplicateCandidates.Contains(pair.Value)
                ? $"{pair.Value}_{ShortHash(pair.Key)}"
                : pair.Value,
            StringComparer.Ordinal);
    }

    private static IReadOnlyDictionary<int, string> BuildMemberNames(
        IEnumerable<CanonicalFieldDescriptor> fields)
    {
        var ordered = fields.OrderBy(static field => field.Id).ToArray();
        var candidates = ordered.ToDictionary(
            static field => field.Id,
            static field => ToPascalIdentifier(field.Name));
        var duplicates = candidates.Values.GroupBy(static value => value, StringComparer.Ordinal)
            .Where(static group => group.Count() > 1)
            .Select(static group => group.Key)
            .ToHashSet(StringComparer.Ordinal);
        return candidates.ToDictionary(
            static pair => pair.Key,
            pair => duplicates.Contains(pair.Value) ? $"{pair.Value}_F{pair.Key}" : pair.Value);
    }

    private static string GetCSharpType(
        CanonicalFieldDescriptor field,
        IReadOnlyDictionary<string, string> typeNames)
    {
        string valueType;
        if (field.Map is { } map)
        {
            var keyType = map.KeyEnumType is not null
                ? ResolveType(map.KeyEnumType, typeNames)
                : ResolveType(map.KeyTypeName, typeNames);
            valueType = $"Dictionary<{keyType}, {ResolveType(map.ValueTypeName, typeNames)}>";
        }
        else
        {
            valueType = ResolveType(field.TypeName, typeNames);
            if (field.Shape is CanonicalFieldShape.RepeatedScalar
                or CanonicalFieldShape.RepeatedEnum
                or CanonicalFieldShape.RepeatedMessage)
            {
                valueType = $"List<{valueType}>";
            }
        }

        var nullable = field.Map is null
            && field.Shape is not (CanonicalFieldShape.RepeatedScalar
                or CanonicalFieldShape.RepeatedEnum
                or CanonicalFieldShape.RepeatedMessage)
            && field.HasPresence;
        return nullable ? $"{valueType}?" : valueType;
    }

    private static string GetInitializer(
        CanonicalFieldDescriptor field,
        IReadOnlyDictionary<string, string> typeNames)
    {
        if (field.HasPresence && field.Map is null)
            return string.Empty;
        if (field.Map is not null
            || field.Shape is CanonicalFieldShape.RepeatedScalar
                or CanonicalFieldShape.RepeatedEnum
                or CanonicalFieldShape.RepeatedMessage)
        {
            return " = new();";
        }

        return field.TypeName switch
        {
            "string" => " = string.Empty;",
            "bytes" => " = Array.Empty<byte>();",
            _ when field.Shape is CanonicalFieldShape.Message or CanonicalFieldShape.OneOfVariant => " = new();",
            _ => string.Empty,
        };
    }

    private static string ResolveType(string typeName, IReadOnlyDictionary<string, string> typeNames)
    {
        if (typeNames.TryGetValue(typeName, out var generated))
            return generated;
        return typeName switch
        {
            "double" => "double",
            "float" => "float",
            "int64" or "sint64" or "sfixed64" => "long",
            "uint64" or "fixed64" => "ulong",
            "int32" or "sint32" or "sfixed32" => "int",
            "uint32" or "fixed32" => "uint",
            "bool" => "bool",
            "string" => "string",
            "bytes" => "byte[]",
            "exceldb.RowRef" => "RowRef",
            "exceldb.UnityResourceRef" => "UnityResourceRef",
            "exceldb.LocalizedTextRef" => "LocalizedTextRef",
            "exceldb.Curve" => "Curve",
            "exceldb.CurvePoint" => "CurvePoint",
            _ => ToPascalIdentifier(typeName[(typeName.LastIndexOf('.') + 1)..]),
        };
    }

    private static bool IsValueTypeName(string typeName) => typeName is
        "double" or "float" or "int64" or "sint64" or "sfixed64"
        or "uint64" or "fixed64" or "int32" or "sint32" or "sfixed32"
        or "uint32" or "fixed32" or "bool"
        or "exceldb.RowRef" or "exceldb.UnityResourceRef" or "exceldb.LocalizedTextRef";

    private static bool IsBuiltInType(string typeName) => typeName.StartsWith("exceldb.", StringComparison.Ordinal);

    private static IEnumerable<CanonicalFieldDescriptor> Flatten(IEnumerable<CanonicalFieldDescriptor> fields)
    {
        foreach (var field in fields)
        {
            yield return field;
            foreach (var child in Flatten(field.Children))
                yield return child;
        }
    }

    private static void AddArtifact(
        ImmutableArray<GeneratedSchemaArtifact>.Builder artifacts,
        string path,
        string kind,
        string? target,
        string content)
    {
        var normalized = NormalizeNewLines(content);
        artifacts.Add(new GeneratedSchemaArtifact(path, kind, target, normalized, Sha256(normalized)));
    }

    private static string ComputeCodegenHash(ImmutableArray<GeneratedSchemaArtifact> artifacts)
    {
        var builder = new StringBuilder();
        foreach (var artifact in artifacts)
            builder.Append(artifact.RelativePath).Append('\0').Append(artifact.ContentHash).Append('\n');
        return Sha256(builder.ToString());
    }

    private static string BuildManifestJson(
        ulong schemaHash,
        string codegenHash,
        string? catalogHash,
        ImmutableArray<GeneratedSchemaArtifact> artifacts)
    {
        var builder = new StringBuilder();
        builder.Append("{\"format\":\"exceldb.codegen-manifest.v1\",\"schemaHash\":")
            .Append(JsonSerializer.Serialize(schemaHash.ToString("x16", CultureInfo.InvariantCulture)))
            .Append(",\"codegenHash\":").Append(JsonSerializer.Serialize(codegenHash));
        if (catalogHash is not null)
        {
            builder.Append(",\"catalogHash\":")
                .Append(JsonSerializer.Serialize(catalogHash));
        }

        builder.Append(",\"artifacts\":[");
        for (var index = 0; index < artifacts.Length; index++)
        {
            if (index != 0)
                builder.Append(',');
            var artifact = artifacts[index];
            builder.Append("{\"path\":").Append(JsonSerializer.Serialize(artifact.RelativePath))
                .Append(",\"kind\":").Append(JsonSerializer.Serialize(artifact.Kind))
                .Append(",\"exportTarget\":").Append(JsonSerializer.Serialize(artifact.ExportTarget))
                .Append(",\"sha256\":").Append(JsonSerializer.Serialize(artifact.ContentHash)).Append('}');
        }

        builder.Append("]}");
        return builder.ToString();
    }

    private static string Sha256(string value) =>
        Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(value))).ToLowerInvariant();

    private static bool IsSha256(string value) =>
        value.Length == 64
        && value.All(static character => character is >= '0' and <= '9' or >= 'a' and <= 'f');

    private static void RequireSafeTargetId(string target)
    {
        if (target.Length == 0
            || target[0] is < 'a' or > 'z'
            || target.Skip(1).Any(static character =>
                character is not (>= 'a' and <= 'z')
                && character is not (>= '0' and <= '9')
                && character != '-'))
        {
            throw new InvalidDataException(
                $"Export target cannot be used as a generated directory segment: '{target}'.");
        }
    }

    private static string ShortHash(string value) => Sha256(value)[..8];

    private static string SafeTargetIdentifier(string target) => $"Target_{ShortHash(target)}";

    private static string ToPascalIdentifier(string value)
    {
        var builder = new StringBuilder(value.Length + 1);
        var upper = true;
        foreach (var character in value)
        {
            if (!char.IsAsciiLetterOrDigit(character) && character != '_')
            {
                upper = true;
                continue;
            }

            if (character == '_')
            {
                upper = true;
                continue;
            }

            builder.Append(upper ? char.ToUpperInvariant(character) : character);
            upper = false;
        }

        if (builder.Length == 0)
            builder.Append("Value");
        if (char.IsDigit(builder[0]))
            builder.Insert(0, '_');
        var result = builder.ToString();
        return CSharpKeywords.Contains(result) ? $"@{result}" : result;
    }

    private static string UniqueIdentifier(string candidate, int identity, HashSet<string> used)
    {
        if (used.Add(candidate))
            return candidate;
        var unique = $"{candidate}_{identity.ToString(CultureInfo.InvariantCulture).Replace('-', '_')}";
        used.Add(unique);
        return unique;
    }

    private static string CSharpString(string value) => JsonSerializer.Serialize(value);

    private static string CSharpNullableString(string? value) =>
        value is null ? "null" : CSharpString(value);

    private static string FormatFieldIdPath(CanonicalFieldDescriptor field) =>
        string.Join(".", field.FieldIdPath);

    private static string IntArrayExpression(IEnumerable<int> values) =>
        $"new int[] {{ {string.Join(", ", values.Select(static value => value.ToString(CultureInfo.InvariantCulture)))} }}";

    private static string StringArrayExpression(IEnumerable<string> values) =>
        $"new string[] {{ {string.Join(", ", values.Select(CSharpString))} }}";

    private static string CodecMethodName(
        int tableId,
        string tableFullName,
        CanonicalFieldDescriptor field) =>
        $"T{Math.Abs((long)tableId).ToString(CultureInfo.InvariantCulture)}_P{string.Join("_", field.FieldIdPath)}_{ShortHash(tableFullName)[..6]}";

    private static string PhysicalKindExpression(CanonicalFieldDescriptor field)
    {
        if (field.ChildTable?.Kind == CanonicalChildTableKind.RepeatedMessage)
            return "GeneratedPhysicalFieldKind.RepeatedMessageChildTable";
        if (field.ChildTable?.Kind == CanonicalChildTableKind.MessageMap)
            return "GeneratedPhysicalFieldKind.MessageMapChildTable";
        if (!field.Children.IsDefaultOrEmpty && field.ExpandMode == CanonicalExpandMode.ExpandedColumns)
            return "GeneratedPhysicalFieldKind.PropertyGroup";
        if (field.FieldIdPath.Length > 1)
            return "GeneratedPhysicalFieldKind.ExpandedColumn";
        return "GeneratedPhysicalFieldKind.Cell";
    }

    private static string BuildMemberPath(
        string propertyPath,
        ImmutableArray<CanonicalFieldDescriptor> topLevelFields,
        IReadOnlyDictionary<int, string> topLevelMembers)
    {
        var segments = propertyPath.Split('.');
        if (segments.Length == 0)
            return propertyPath;
        var top = topLevelFields.FirstOrDefault(field =>
            string.Equals(field.Name, segments[0], StringComparison.Ordinal));
        var first = top is not null && topLevelMembers.TryGetValue(top.Id, out var member)
            ? member
            : ToPascalIdentifier(segments[0]);
        if (segments.Length == 1)
            return first;
        return $"{first}.{string.Join(".", segments.Skip(1).Select(ToPascalIdentifier))}";
    }

    private static string NormalizeNewLines(string value) =>
        value.Replace("\r\n", "\n", StringComparison.Ordinal).Replace('\r', '\n');

