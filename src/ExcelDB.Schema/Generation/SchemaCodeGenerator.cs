        builder.AppendLine("            if (property.GetIndexParameters().Length == 0 && property.GetMethod is not null) CollectDependencies(property.GetValue(value, null), result, visited);");
        builder.AppendLine("    }");
        builder.AppendLine("    private sealed class ReferenceComparer : IEqualityComparer<object>");
        builder.AppendLine("    {");
        builder.AppendLine("        public static ReferenceComparer Instance { get; } = new ReferenceComparer();");
        builder.AppendLine("        public new bool Equals(object? left, object? right) => ReferenceEquals(left, right);");
        builder.AppendLine("        public int GetHashCode(object value) => RuntimeHelpers.GetHashCode(value);");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        builder.AppendLine("}");
        return NormalizeNewLines(builder.ToString());
    }

    private static void AppendRuntimeFieldAssignment(
        StringBuilder builder,
        CanonicalTableDescriptor table,
        CanonicalFieldDescriptor field,
        IReadOnlyDictionary<string, string> typeNames)
    {
        var chain = ResolveFieldChain(table, field);
        var path = field.FieldIdPath.IsDefaultOrEmpty ? [field.Id] : field.FieldIdPath;
        builder.Append("            if (field.FieldIdPath.Length == ")
            .Append(path.Length.ToString(CultureInfo.InvariantCulture));
        for (var index = 0; index < path.Length; index++)
        {
            builder.Append(" && field.FieldIdPath[")
                .Append(index.ToString(CultureInfo.InvariantCulture))
                .Append("] == ")
                .Append(path[index].ToString(CultureInfo.InvariantCulture));
        }
        builder.AppendLine(")");
        builder.AppendLine("            {");

        var access = "instance";
        var siblings = table.Fields;
        for (var index = 0; index < chain.Length; index++)
        {
            var descriptor = chain[index];
            var member = BuildMemberNames(siblings)[descriptor.Id];
            access += "." + member;
            if (index < chain.Length - 1)
            {
                builder.Append("                if (").Append(access).Append(" is null) ")
                    .Append(access).Append(" = new ")
                    .Append(ResolveType(descriptor.TypeName, typeNames)).AppendLine("();");
            }
            siblings = descriptor.Children;
        }

        builder.Append("                ").Append(access)
            .Append(" = RuntimeGeneratedValueCodec.Parse<")
            .Append(GetCSharpType(field, typeNames)).AppendLine(">(field.Data.Span);");
        builder.AppendLine("                continue;");
        builder.AppendLine("            }");
    }

    private static ImmutableArray<CanonicalFieldDescriptor> ResolveFieldChain(
        CanonicalTableDescriptor table,
        CanonicalFieldDescriptor leaf)
    {
        var path = leaf.FieldIdPath.IsDefaultOrEmpty ? [leaf.Id] : leaf.FieldIdPath;
        var result = ImmutableArray.CreateBuilder<CanonicalFieldDescriptor>(path.Length);
        var siblings = table.Fields;
        foreach (var fieldId in path)
        {
            var descriptor = siblings.FirstOrDefault(candidate => candidate.Id == fieldId)
                ?? throw new InvalidOperationException(
                    $"Field path '{string.Join('.', path)}' is not rooted in table '{table.FullName}'.");
            result.Add(descriptor);
            siblings = descriptor.Children;
        }
        return result.ToImmutable();
    }

    private static bool IsRuntimeRecordField(
        CanonicalTableDescriptor table,
        CanonicalFieldDescriptor field)
    {
        var chain = ResolveFieldChain(table, field);
        // Child-table rows are aggregated into one canonical JSON value at the
        // owner field before conversion. RuntimeAssetRecord therefore contains
        // the repeated/map owner path, never its worksheet-only descendant
        // columns. Expanded singular messages are different: their descendant
        // paths are physical runtime fields and must remain assignable.
        return chain.Length == 1 || chain[0].ChildTable is null;
    }

    private static Dictionary<string, ShapeDefinition> CollectDefinitions(
        CanonicalSchemaDescriptor descriptor,
        string? target)
    {
        var result = new Dictionary<string, ShapeDefinition>(StringComparer.Ordinal);
        foreach (var table in descriptor.Tables
                     .Where(table => target is null || table.ExportTargets.Contains(target, StringComparer.Ordinal)))
        {
            AddDefinition(result, table.FullName, table.Id, table.Fields, target);
        }

        return result;
    }

    private static void AddDefinition(
        Dictionary<string, ShapeDefinition> result,
        string fullName,
        int? tableId,
        IEnumerable<CanonicalFieldDescriptor> fields,
        string? target)
    {
        if (!result.TryGetValue(fullName, out var definition))
        {
            definition = new ShapeDefinition(fullName, tableId);
            result.Add(fullName, definition);
        }

        foreach (var field in fields.OrderBy(static item => item.Id))
        {
            if (target is not null && !field.ExportTargets.Contains(target, StringComparer.Ordinal))
                continue;
            definition.Fields.TryAdd(field.Id, field);

            var messageType = field.Map?.ValueShape == CanonicalFieldShape.Message
                ? field.Map.ValueTypeName
                : field.Shape is CanonicalFieldShape.Message
                    or CanonicalFieldShape.RepeatedMessage
                    or CanonicalFieldShape.OneOfVariant
                    ? field.TypeName
                    : null;
            if (messageType is null || IsBuiltInType(messageType) || field.Children.IsEmpty)
                continue;
            AddDefinition(result, messageType, null, field.Children, target);
        }
    }

    private static IReadOnlyDictionary<string, string> BuildTypeNames(
        CanonicalSchemaDescriptor descriptor,
        IEnumerable<string> messageNames)
    {
        var fullNames = messageNames.Concat(descriptor.Enums.Select(static item => item.FullName))
            .Distinct(StringComparer.Ordinal)
            .OrderBy(static value => value, StringComparer.Ordinal)
            .ToArray();
        var candidates = fullNames.ToDictionary(
            static fullName => fullName,
            static fullName => ToPascalIdentifier(fullName[(fullName.LastIndexOf('.') + 1)..]),
            StringComparer.Ordinal);
        var duplicateCandidates = candidates.Values
            .GroupBy(static value => value, StringComparer.Ordinal)
            .Where(static group => group.Count() > 1)
            .Select(static group => group.Key)
            .ToHashSet(StringComparer.Ordinal);
        return candidates.ToDictionary(
            static pair => pair.Key,
            pair => duplicateCandidates.Contains(pair.Value)
                ? $"{pair.Value}_{ShortHash(pair.Key)}"
                : pair.Value,
            StringComparer.Ordinal);
    }

    private static IReadOnlyDictionary<int, string> BuildMemberNames(
        IEnumerable<CanonicalFieldDescriptor> fields)
    {
        var ordered = fields.OrderBy(static field => field.Id).ToArray();
        var candidates = ordered.ToDictionary(
            static field => field.Id,
            static field => ToPascalIdentifier(field.Name));
        var duplicates = candidates.Values.GroupBy(static value => value, StringComparer.Ordinal)
            .Where(static group => group.Count() > 1)
            .Select(static group => group.Key)
            .ToHashSet(StringComparer.Ordinal);
        return candidates.ToDictionary(
            static pair => pair.Key,
            pair => duplicates.Contains(pair.Value) ? $"{pair.Value}_F{pair.Key}" : pair.Value);
    }

    private static string GetCSharpType(
        CanonicalFieldDescriptor field,
        IReadOnlyDictionary<string, string> typeNames)
    {
        string valueType;
        if (field.Map is { } map)
        {
            var keyType = map.KeyEnumType is not null
                ? ResolveType(map.KeyEnumType, typeNames)
                : ResolveType(map.KeyTypeName, typeNames);
            valueType = $"Dictionary<{keyType}, {ResolveType(map.ValueTypeName, typeNames)}>";
        }
        else
        {
            valueType = ResolveType(field.TypeName, typeNames);
            if (field.Shape is CanonicalFieldShape.RepeatedScalar
                or CanonicalFieldShape.RepeatedEnum
                or CanonicalFieldShape.RepeatedMessage)
            {
                valueType = $"List<{valueType}>";
            }
        }

        var nullable = field.Map is null
            && field.Shape is not (CanonicalFieldShape.RepeatedScalar
                or CanonicalFieldShape.RepeatedEnum
                or CanonicalFieldShape.RepeatedMessage)
            && field.HasPresence;
        return nullable ? $"{valueType}?" : valueType;
    }

    private static string GetInitializer(
        CanonicalFieldDescriptor field,
        IReadOnlyDictionary<string, string> typeNames)
    {
        if (field.Map is not null
            || field.Shape is CanonicalFieldShape.RepeatedScalar
                or CanonicalFieldShape.RepeatedEnum
                or CanonicalFieldShape.RepeatedMessage)
        {
            return " = new();";
        }

        if (field.HasPresence)
            return string.Empty;

        return field.TypeName switch
        {
            "string" => " = string.Empty;",
            "bytes" => " = Array.Empty<byte>();",
            _ when field.Shape is CanonicalFieldShape.Message or CanonicalFieldShape.OneOfVariant => " = new();",
            _ => string.Empty,
        };
    }

    private static string ResolveType(string typeName, IReadOnlyDictionary<string, string> typeNames)
    {
        if (typeNames.TryGetValue(typeName, out var generated))
            return generated;
        return typeName switch
        {
            "double" => "double",
            "float" => "float",
            "int64" or "sint64" or "sfixed64" => "long",
            "uint64" or "fixed64" => "ulong",
            "int32" or "sint32" or "sfixed32" => "int",
            "uint32" or "fixed32" => "uint",
            "bool" => "bool",
            "string" => "string",
            "bytes" => "byte[]",
            "exceldb.RowRef" => "RowRef",
            "exceldb.UnityResourceRef" => "UnityResourceRef",
            "exceldb.LocalizedTextRef" => "LocalizedTextRef",
            "exceldb.Curve" => "Curve",
            "exceldb.CurvePoint" => "CurvePoint",
            _ => ToPascalIdentifier(typeName[(typeName.LastIndexOf('.') + 1)..]),
        };
    }

    private static bool IsValueTypeName(string typeName) => typeName is
        "double" or "float" or "int64" or "sint64" or "sfixed64"
        or "uint64" or "fixed64" or "int32" or "sint32" or "sfixed32"
        or "uint32" or "fixed32" or "bool"
        or "exceldb.RowRef" or "exceldb.UnityResourceRef" or "exceldb.LocalizedTextRef";

    private static bool IsBuiltInType(string typeName) => typeName.StartsWith("exceldb.", StringComparison.Ordinal);

    private static IEnumerable<CanonicalFieldDescriptor> Flatten(IEnumerable<CanonicalFieldDescriptor> fields)
    {
        foreach (var field in fields)
        {
            yield return field;
            foreach (var child in Flatten(field.Children))
                yield return child;
        }
    }

    private static void AddArtifact(
        ImmutableArray<GeneratedSchemaArtifact>.Builder artifacts,
        string path,
        string kind,
        string? target,
        string content)
    {
        var normalized = NormalizeNewLines(content);
        artifacts.Add(new GeneratedSchemaArtifact(path, kind, target, normalized, Sha256(normalized)));
    }

    private static string ComputeCodegenHash(ImmutableArray<GeneratedSchemaArtifact> artifacts)
    {
        var builder = new StringBuilder();
        foreach (var artifact in artifacts)
            builder.Append(artifact.RelativePath).Append('\0').Append(artifact.ContentHash).Append('\n');
        return Sha256(builder.ToString());
    }

    private static string BuildManifestJson(
        ulong schemaHash,
        string codegenHash,
        string? catalogHash,
        ImmutableArray<GeneratedSchemaArtifact> artifacts)
    {
        var builder = new StringBuilder();
        builder.Append("{\"format\":\"exceldb.codegen-manifest.v1\",\"schemaHash\":")
            .Append(JsonSerializer.Serialize(schemaHash.ToString("x16", CultureInfo.InvariantCulture)))
            .Append(",\"codegenHash\":").Append(JsonSerializer.Serialize(codegenHash));
        if (catalogHash is not null)
        {
            builder.Append(",\"catalogHash\":")
                .Append(JsonSerializer.Serialize(catalogHash));
        }

        builder.Append(",\"artifacts\":[");
        for (var index = 0; index < artifacts.Length; index++)
        {
            if (index != 0)
                builder.Append(',');
            var artifact = artifacts[index];
            builder.Append("{\"path\":").Append(JsonSerializer.Serialize(artifact.RelativePath))
                .Append(",\"kind\":").Append(JsonSerializer.Serialize(artifact.Kind))
                .Append(",\"exportTarget\":").Append(JsonSerializer.Serialize(artifact.ExportTarget))
                .Append(",\"sha256\":").Append(JsonSerializer.Serialize(artifact.ContentHash)).Append('}');
        }

        builder.Append("]}");
        return builder.ToString();
    }

    private static string Sha256(string value) =>
        Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(value))).ToLowerInvariant();

    private static bool IsSha256(string value) =>
        value.Length == 64
        && value.All(static character => character is >= '0' and <= '9' or >= 'a' and <= 'f');

    private static void RequireSafeTargetId(string target)
    {
        if (target.Length == 0
            || target[0] is < 'a' or > 'z'
            || target.Skip(1).Any(static character =>
                character is not (>= 'a' and <= 'z')
                && character is not (>= '0' and <= '9')
                && character != '-'))
        {
            throw new InvalidDataException(
                $"Export target cannot be used as a generated directory segment: '{target}'.");
        }
    }

    private static string ShortHash(string value) => Sha256(value)[..8];

    private static string SafeTargetIdentifier(string target) => $"Target_{ShortHash(target)}";

    private static string ToPascalIdentifier(string value)
    {
        var builder = new StringBuilder(value.Length + 1);
        var upper = true;
        foreach (var character in value)
        {
            if (!char.IsAsciiLetterOrDigit(character) && character != '_')
            {
                upper = true;
                continue;
            }

            if (character == '_')
            {
                upper = true;
                continue;
            }

            builder.Append(upper ? char.ToUpperInvariant(character) : character);
            upper = false;
        }

        if (builder.Length == 0)
            builder.Append("Value");
        if (char.IsDigit(builder[0]))
            builder.Insert(0, '_');
        var result = builder.ToString();
        return CSharpKeywords.Contains(result) ? $"@{result}" : result;
    }

    private static string UniqueIdentifier(string candidate, int identity, HashSet<string> used)
    {
        if (used.Add(candidate))
            return candidate;
        var unique = $"{candidate}_{identity.ToString(CultureInfo.InvariantCulture).Replace('-', '_')}";
        used.Add(unique);
        return unique;
    }

    private static string CSharpString(string value) => JsonSerializer.Serialize(value);

    private static string CSharpNullableString(string? value) =>
        value is null ? "null" : CSharpString(value);

    private static string FormatFieldIdPath(CanonicalFieldDescriptor field) =>
        string.Join(".", field.FieldIdPath);

    private static string IntArrayExpression(IEnumerable<int> values) =>
        $"new int[] {{ {string.Join(", ", values.Select(static value => value.ToString(CultureInfo.InvariantCulture)))} }}";

    private static string StringArrayExpression(IEnumerable<string> values) =>
        $"new string[] {{ {string.Join(", ", values.Select(CSharpString))} }}";

    private static string CodecMethodName(
        int tableId,
        string tableFullName,
        CanonicalFieldDescriptor field) =>
        $"T{Math.Abs((long)tableId).ToString(CultureInfo.InvariantCulture)}_P{string.Join("_", field.FieldIdPath)}_{ShortHash(tableFullName)[..6]}";

    private static string PhysicalKindExpression(CanonicalFieldDescriptor field)
    {
        if (field.ChildTable?.Kind == CanonicalChildTableKind.RepeatedMessage)
            return "GeneratedPhysicalFieldKind.RepeatedMessageChildTable";
        if (field.ChildTable?.Kind == CanonicalChildTableKind.MessageMap)
            return "GeneratedPhysicalFieldKind.MessageMapChildTable";
        if (!field.Children.IsDefaultOrEmpty && field.ExpandMode == CanonicalExpandMode.ExpandedColumns)
            return "GeneratedPhysicalFieldKind.PropertyGroup";
        if (field.FieldIdPath.Length > 1)
            return "GeneratedPhysicalFieldKind.ExpandedColumn";
        return "GeneratedPhysicalFieldKind.Cell";
    }

    private static string FieldShapeExpression(CanonicalFieldShape shape) => shape switch
    {
        CanonicalFieldShape.Scalar => "GeneratedFieldShape.Scalar",
        CanonicalFieldShape.Enum => "GeneratedFieldShape.Enum",
        CanonicalFieldShape.Message => "GeneratedFieldShape.Message",
        CanonicalFieldShape.RepeatedScalar => "GeneratedFieldShape.RepeatedScalar",
        CanonicalFieldShape.RepeatedEnum => "GeneratedFieldShape.RepeatedEnum",
        CanonicalFieldShape.RepeatedMessage => "GeneratedFieldShape.RepeatedMessage",
        CanonicalFieldShape.Map => "GeneratedFieldShape.Map",
        CanonicalFieldShape.OneOfVariant => "GeneratedFieldShape.OneOfVariant",
        _ => throw new ArgumentOutOfRangeException(nameof(shape), shape, "Unknown canonical field shape."),
    };

    private static string BuildMemberPath(
        CanonicalTableDescriptor table,
        CanonicalFieldDescriptor field)
    {
        var chain = ResolveFieldChain(table, field);
        var members = new string[chain.Length];
        var siblings = table.Fields;
        for (var index = 0; index < chain.Length; index++)
        {
            var descriptor = chain[index];
            members[index] = BuildMemberNames(siblings)[descriptor.Id];
            siblings = descriptor.Children;
        }

        return string.Join(".", members);
    }

    private static string NormalizeNewLines(string value) =>
        value.Replace("\r\n", "\n", StringComparison.Ordinal).Replace('\r', '\n');

