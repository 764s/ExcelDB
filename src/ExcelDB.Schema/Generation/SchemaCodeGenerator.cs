namespace ExcelDb.Schema.Generation;

public sealed record GeneratedSchemaArtifact(
    string RelativePath,
    string Kind,
    string? ExportTarget,
    string Content,
    string ContentHash);

public sealed record SchemaArtifactManifest(
    ulong SchemaHash,
    string CodegenHash,
    string Json,
    string ManifestHash,
    string? CatalogHash = null);

public sealed record SchemaCodeGenerationResult(
    ImmutableArray<GeneratedSchemaArtifact> Artifacts,
    SchemaArtifactManifest Manifest);

/// <summary>
/// Deterministically projects the canonical descriptor into full authoring C# and
/// isolated per-target runtime C#. It is deliberately pure: callers own atomic IO.
/// </summary>
public sealed class SchemaCodeGenerator
{
    public SchemaCodeGenerationResult Generate(CanonicalSchemaDescriptor descriptor) =>
        Generate(descriptor, catalogHash: null);

    /// <summary>
    /// Generates canonical artifacts and records the executable system-proto
    /// catalog identity in the ownership manifest when supplied.
    /// </summary>
    public SchemaCodeGenerationResult Generate(
        CanonicalSchemaDescriptor descriptor,
        string? catalogHash)
    {
        ArgumentNullException.ThrowIfNull(descriptor);
        if (catalogHash is not null && !IsSha256(catalogHash))
        {
            throw new ArgumentException(
                "Catalog hash must be a lower-case SHA-256 value.",
                nameof(catalogHash));
        }

        var allDefinitions = CollectDefinitions(descriptor, target: null);
        var allTypeNames = BuildTypeNames(descriptor, allDefinitions.Keys);
        var artifacts = ImmutableArray.CreateBuilder<GeneratedSchemaArtifact>();
        AddArtifact(
            artifacts,
            "Authoring/ExcelDbSchema.Authoring.g.cs",
            "authoring-csharp",
            null,
            GenerateSurface(descriptor, null, allDefinitions, allTypeNames));

        var targets = descriptor.Tables
            .SelectMany(static table => table.ExportTargets)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(static value => value, StringComparer.Ordinal)
            .ToArray();
        foreach (var target in targets)
        {
            RequireSafeTargetId(target);
            var definitions = CollectDefinitions(descriptor, target);
            var safeTarget = SafeTargetIdentifier(target);
            var prefix = $"Runtime/{target}";
            AddArtifact(
                artifacts,
                $"{prefix}/ExcelDbSchema.Runtime.{safeTarget}.g.cs",
                "runtime-csharp",
                target,
                GenerateSurface(descriptor, target, definitions, allTypeNames));
            AddArtifact(
                artifacts,
                $"{prefix}/RuntimeSchemaRegistry.{safeTarget}.g.cs",
                "runtime-registry-csharp",
                target,
                GenerateRegistry(descriptor, target, safeTarget, allTypeNames));
        }

        var ordered = artifacts
            .OrderBy(static artifact => artifact.RelativePath, StringComparer.Ordinal)
            .ToImmutableArray();
        var codegenHash = ComputeCodegenHash(ordered);
        var manifestJson = BuildManifestJson(
            descriptor.SchemaHash,
            codegenHash,
            catalogHash,
            ordered);
        var manifestHash = Sha256(manifestJson);
        return new SchemaCodeGenerationResult(
            ordered,
            new SchemaArtifactManifest(
                descriptor.SchemaHash,
                codegenHash,
                manifestJson,
                manifestHash,
                catalogHash));
    }

    private static string GenerateSurface(
        CanonicalSchemaDescriptor descriptor,
        string? target,
        IReadOnlyDictionary<string, ShapeDefinition> definitions,
        IReadOnlyDictionary<string, string> typeNames)
    {
        var builder = new StringBuilder();
        var namespaceName = target is null
            ? "ExcelDb.Generated.Authoring"
            : $"ExcelDb.Generated.Runtime.{SafeTargetIdentifier(target)}";
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using System;");
        builder.AppendLine("using System.Collections.Generic;");
        builder.AppendLine("using System.Globalization;");
        builder.AppendLine("using System.Text;");
        builder.AppendLine("using System.Text.Json;");
        if (target is not null)
        {
            builder.AppendLine("using ExcelDb.Core.Identity;");
            builder.AppendLine("using ExcelDb.Runtime;");
        }
        builder.AppendLine();
        builder.Append("namespace ").Append(namespaceName).AppendLine();
        builder.AppendLine("{");
        builder.AppendLine();
        AppendSupportContracts(builder, target is not null);

        var usedEnums = target is null
            ? descriptor.Enums.Select(static item => item.FullName).ToHashSet(StringComparer.Ordinal)
            : definitions.Values.SelectMany(static definition => definition.Fields.Values)
                .SelectMany(static field => field.Map?.KeyEnumType is { } keyEnum
                    ? new[] { field.TypeName, keyEnum }
                    : new[] { field.TypeName })
                .ToHashSet(StringComparer.Ordinal);
        foreach (var enumDescriptor in descriptor.Enums
                     .Where(item => usedEnums.Contains(item.FullName))
                     .OrderBy(static item => item.FullName, StringComparer.Ordinal))
            AppendEnum(builder, enumDescriptor, typeNames[enumDescriptor.FullName]);

        foreach (var definition in definitions.Values.OrderBy(static item => item.FullName, StringComparer.Ordinal))
        {
            AppendPoco(
                builder,
                definition,
                typeNames[definition.FullName],
                typeNames,
                target);
        }

        if (target is null)
            AppendSurfaceBindings(builder, descriptor, null, typeNames);
        else
            AppendRuntimeBindings(builder, descriptor, target, typeNames);
        builder.AppendLine("}");
        return NormalizeNewLines(builder.ToString());
    }

