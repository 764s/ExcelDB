    private static void AppendEnum(
        StringBuilder builder,
        CanonicalEnumDescriptor descriptor,
        string typeName)
    {
        builder.Append("public enum ").Append(typeName).AppendLine();
        builder.AppendLine("{");
        var used = new HashSet<string>(StringComparer.Ordinal);
        foreach (var value in descriptor.Values)
        {
            var name = UniqueIdentifier(ToPascalIdentifier(value.Name), value.Number, used);
            builder.Append("    ").Append(name).Append(" = ")
                .Append(value.Number.ToString(CultureInfo.InvariantCulture)).AppendLine(",");
        }

        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void AppendPoco(
        StringBuilder builder,
        ShapeDefinition definition,
        string typeName,
        IReadOnlyDictionary<string, string> typeNames,
        string? target)
    {
        if (definition.TableId is { } tableId)
        {
            builder.Append("[GeneratedTable(")
                .Append(tableId.ToString(CultureInfo.InvariantCulture)).Append(", ")
                .Append(CSharpString(definition.FullName)).AppendLine(")] ");
        }

        builder.Append("public sealed partial class ").Append(typeName).AppendLine();
        builder.AppendLine("{");
        var fields = definition.Fields.Values
            .Where(field => target is null || field.ExportTargets.Contains(target, StringComparer.Ordinal))
            .OrderBy(static field => field.Id)
            .ToArray();
        var memberNames = BuildMemberNames(fields);
        foreach (var group in fields
                     .Where(static field => field.OneOfGroup is not null)
                     .GroupBy(static field => field.OneOfGroup!, StringComparer.Ordinal)
                     .OrderBy(static group => group.Key, StringComparer.Ordinal))
        {
            builder.Append("    public int ")
                .Append(ToPascalIdentifier(group.Key)).AppendLine("VariantId { get; set; }");
        }

        foreach (var field in fields)
        {
            var memberName = memberNames[field.Id];
            builder.Append("    [GeneratedField(")
                .Append(field.Id.ToString(CultureInfo.InvariantCulture)).Append(", ")
                .Append(CSharpString(FormatFieldIdPath(field))).Append(", ")
                .Append(CSharpString(field.PropertyPath)).AppendLine(")] ");
            builder.Append("    public ").Append(GetCSharpType(field, typeNames))
                .Append(' ').Append(memberName).Append(" { get; set; }")
                .Append(GetInitializer(field, typeNames)).AppendLine();
        }

        builder.AppendLine("}");
        builder.AppendLine();
    }

    private static void AppendSurfaceBindings(
        StringBuilder builder,
        CanonicalSchemaDescriptor descriptor,
        string? target,
        IReadOnlyDictionary<string, string> typeNames)
    {
        var tables = descriptor.Tables
            .Where(table => target is null || table.ExportTargets.Contains(target, StringComparer.Ordinal))
            .OrderBy(static table => table.Id)
            .ThenBy(static table => table.FullName, StringComparer.Ordinal)
            .ToArray();
        builder.AppendLine("public static class GeneratedSchemaBindings");
        builder.AppendLine("{");
        builder.AppendLine("    public static IReadOnlyList<GeneratedTableBinding> Tables { get; } = Array.AsReadOnly(new GeneratedTableBinding[]");
        builder.AppendLine("    {");
        foreach (var table in tables)
        {
            var fields = Flatten(table.Fields)
                .Where(field => target is null || field.ExportTargets.Contains(target, StringComparer.Ordinal))
                .OrderBy(static field => field.PropertyPath, StringComparer.Ordinal)
                .ThenBy(static field => field.Id)
                .ToArray();
            builder.Append("        new(")
                .Append(table.Id.ToString(CultureInfo.InvariantCulture)).Append(", ")
                .Append(CSharpString(table.FullName)).Append(", ")
                .Append(CSharpNullableString(table.DisplayName)).Append(", typeof(")
                .Append(typeNames[table.FullName]).Append("), ")
                .Append(CSharpString($"factory:{table.Id}")).Append(", ")
                .Append(CSharpString($"accessor:{table.Id}")).Append(", ")
                .Append(CSharpString($"patcher:{table.Id}")).Append(", ")
                .Append(StringArrayExpression(table.Implements)).AppendLine(", Array.AsReadOnly(new GeneratedFieldBinding[]");
            builder.AppendLine("        {");
            foreach (var field in fields)
            {
                var member = BuildMemberPath(table, field);
                var codecName = CodecMethodName(table.Id, table.FullName, field);
                var fieldType = GetCSharpType(field, typeNames);
                var child = field.ChildTable;
                builder.Append("            new(")
                    .Append(field.Id.ToString(CultureInfo.InvariantCulture)).Append(", ")
                    .Append(IntArrayExpression(field.FieldIdPath)).Append(", ")
                    .Append(CSharpString(field.PropertyPath)).Append(", ")
                    .Append(CSharpString(member)).Append(", ")
                    .Append(CSharpNullableString(field.DisplayName)).Append(", ")
                    .Append(CSharpNullableString(field.HeaderComment)).Append(", ")
                    .Append(StringArrayExpression(field.Aliases)).Append(", ")
                    .Append(PhysicalKindExpression(field)).Append(", ")
                    .Append(FieldShapeExpression(field.Shape)).Append(", ")
                    .Append(field.HasPresence ? "true" : "false").Append(", ")
                    .Append(field.Required ? "true" : "false").Append(", ")
                    .Append(field.KeyOrder.ToString(CultureInfo.InvariantCulture)).Append(", ")
                    .Append(CSharpNullableString(field.ReferenceTable)).Append(", ")
                    .Append(CSharpNullableString(field.ReferenceGroup)).Append(", ")
                    .Append(CSharpNullableString(child?.SheetName)).Append(", ")
                    .Append(CSharpNullableString(child?.ParentGuidColumn)).Append(", ")
                    .Append(CSharpNullableString(child?.OrdinalColumn)).Append(", ")
                    .Append(CSharpNullableString(child?.MapKeyColumn)).Append(", ")
                    .Append("static text => GeneratedAuthoringCellCodecs.").Append(codecName)
                    .Append("_Parse(text), static value => GeneratedAuthoringCellCodecs.").Append(codecName)
                    .Append("_Write((").Append(fieldType).Append(")value!), ")
                    .Append(CSharpString($"accessor:{table.Id}:{field.PropertyPath}")).Append(", ")
                    .Append(CSharpString($"patcher:{table.Id}:{field.PropertyPath}")).AppendLine("),");
            }

            builder.AppendLine("        })),");
        }

        builder.AppendLine("    });");
        builder.AppendLine("}");
        builder.AppendLine();
        builder.AppendLine("public static class GeneratedAuthoringCellCodecs");
        builder.AppendLine("{");
        foreach (var table in tables)
        {
            foreach (var field in Flatten(table.Fields)
                         .OrderBy(static field => string.Join(".", field.FieldIdPath), StringComparer.Ordinal))
            {
                var codecName = CodecMethodName(table.Id, table.FullName, field);
                var fieldType = GetCSharpType(field, typeNames);
                builder.Append("    public static ").Append(fieldType).Append(' ').Append(codecName)
                    .Append("_Parse(string text) => GeneratedCanonicalCellCodec.Parse<")
                    .Append(fieldType).AppendLine(">(text);");
                builder.Append("    public static string ").Append(codecName).Append("_Write(")
                    .Append(fieldType).Append(" value) => GeneratedCanonicalCellCodec.Write(value);")
                    .AppendLine();
            }
        }
        builder.AppendLine("}");
    }

    private static void AppendRuntimeBindings(
        StringBuilder builder,
        CanonicalSchemaDescriptor descriptor,
        string target,
        IReadOnlyDictionary<string, string> typeNames)
    {
        var tables = descriptor.Tables
            .Where(table => table.Kind == CanonicalTableKind.Asset
                && table.ExportTargets.Contains(target, StringComparer.Ordinal))
            .OrderBy(static table => table.Id)
            .ToArray();

        builder.AppendLine("internal static class RuntimeGeneratedValueCodec");
        builder.AppendLine("{");
        builder.AppendLine("    private static readonly JsonSerializerOptions JsonOptions = new JsonSerializerOptions { PropertyNameCaseInsensitive = true, PropertyNamingPolicy = JsonNamingPolicy.SnakeCaseLower };");
        builder.AppendLine("    public static T Parse<T>(ReadOnlySpan<byte> data)");
        builder.AppendLine("    {");
        builder.AppendLine("        var declared = typeof(T);");
        builder.AppendLine("        var type = Nullable.GetUnderlyingType(declared) ?? declared;");
        builder.AppendLine("        if (data.IsEmpty && Nullable.GetUnderlyingType(declared) is not null) return default!;");
        builder.AppendLine("        if (type == typeof(byte[])) return (T)(object)data.ToArray();");
