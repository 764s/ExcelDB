    private sealed class CatalogSnapshot : ISystemProtoCatalog
    {
        private readonly IReadOnlyDictionary<string, SystemProtoFile> _byPath;

        private CatalogSnapshot(IEnumerable<SystemProtoFile> files)
        {
            Files = files.OrderBy(static file => file.LogicalPath, StringComparer.Ordinal).ToArray();
            _byPath = Files.ToDictionary(static file => file.LogicalPath, StringComparer.Ordinal);
            using var hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
            foreach (var file in Files)
            {
                hash.AppendData(Encoding.UTF8.GetBytes(file.LogicalPath));
                hash.AppendData([0]);
                hash.AppendData(Encoding.ASCII.GetBytes(file.Sha256));
                hash.AppendData([(byte)'\n']);
            }
            CatalogHash = Convert.ToHexString(hash.GetHashAndReset()).ToLowerInvariant();
        }

        public IReadOnlyList<SystemProtoFile> Files { get; }

        public string CatalogHash { get; }

        public bool TryGetFile(string logicalPath, [NotNullWhen(true)] out SystemProtoFile? file) =>
            _byPath.TryGetValue(logicalPath, out file);

        public static CatalogSnapshot WithChangedAndRetiredGoogleProto(ISystemProtoCatalog current)
        {
            var files = current.Files.Select(file =>
                string.Equals(file.LogicalPath, "google/protobuf/empty.proto", StringComparison.Ordinal)
                    ? new SystemProtoFile(
                        file.LogicalPath,
                        [.. file.CanonicalBytes.ToArray(), .. Encoding.UTF8.GetBytes("\n// old catalog payload\n")])
                    : file).ToList();
            files.Add(new SystemProtoFile(
                "google/protobuf/exceldb-retired.proto",
                Encoding.UTF8.GetBytes("syntax = \"proto3\"; package google.protobuf;\n")));
            return new CatalogSnapshot(files);
        }
    }

