    private static ImmutableArray<string> SnapshotTree(string root)
    {
        if (!Directory.Exists(root))
            return [];
        return Directory.EnumerateFileSystemEntries(root, "*", SearchOption.AllDirectories)
            .Prepend(root)
            .Order(StringComparer.Ordinal)
            .Select(path =>
            {
                var relative = path == root ? "." : Normalize(Path.GetRelativePath(root, path));
                var attributes = File.GetAttributes(path);
                if ((attributes & FileAttributes.Directory) != 0)
                {
                    return $"D|{relative}|{(int)attributes}";
                }
                var info = new FileInfo(path);
                var hash = Convert.ToHexStringLower(SHA256.HashData(File.ReadAllBytes(path)));
                return $"F|{relative}|{(int)attributes}|{info.Length}|{info.LastWriteTimeUtc.Ticks}|{hash}";
            })
            .ToImmutableArray();
    }

