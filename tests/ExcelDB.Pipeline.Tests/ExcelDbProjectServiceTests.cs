        Initialize(service);
        await CreateHeroAsync(service);
        Directory.CreateDirectory(_externalCSharp);
        var generatedRoot = Path.Combine(_root, "Generated", "CSharp");
        var artifactPath = Path.Combine(generatedRoot, "Authoring", "ExcelDbSchema.Authoring.g.cs");
        var manifestPath = Path.Combine(generatedRoot, "codegen.manifest.json");
        var artifactBytes = File.ReadAllBytes(artifactPath);
        var manifestBytes = File.ReadAllBytes(manifestPath);
        var outsideArtifact = Path.Combine(_externalCSharp, "artifact.cs");
