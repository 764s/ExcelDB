    [Fact]
    public async Task Inspect_maps_codegen_pending_and_exact_bytes_facts_to_cards_and_actions()
    {
        var service = CreateService();
        Initialize(service);
        await CreateHeroAsync(service);

        var missingBytes = service.Inspect(Location);
        Assert.Equal(ProjectStatus.BytesGenerationRequired, missingBytes.Status);
        Assert.Equal(1, missingBytes.Schema.ItemCount);
        Assert.DoesNotContain("Regeneration required", missingBytes.GeneratedCSharp.Status, StringComparison.Ordinal);
        Assert.Equal(2, missingBytes.GeneratedByteTargets.Length);
        Assert.All(missingBytes.GeneratedByteTargets, target =>
            Assert.Equal(ProjectTargetArtifactStatus.Missing, target.Status));
        Assert.True(missingBytes.Actions.Convert.Enabled);

        var generatedPath = Path.Combine(
            _root,
            "Generated",
            "CSharp",
            "Authoring",
            "ExcelDbSchema.Authoring.g.cs");
        var generatedBefore = File.ReadAllBytes(generatedPath);
        File.AppendAllText(generatedPath, "// modified\n", new UTF8Encoding(false));
        var staleCodegen = service.Inspect(Location);
        Assert.Equal(ProjectStatus.RegenerationRequired, staleCodegen.Status);
        Assert.Contains("Regeneration required", staleCodegen.GeneratedCSharp.Status, StringComparison.Ordinal);
        Assert.True(staleCodegen.Actions.Regenerate.Enabled);
        Assert.False(staleCodegen.Actions.Convert.Enabled);

        File.WriteAllBytes(generatedPath, generatedBefore);
        var workbookPath = Path.Combine(_root, "Excel", "game.xlsx");
        AddPendingRow(workbookPath, "hero-1", "First");
        var pending = service.Inspect(Location);
        Assert.Equal(ProjectStatus.PendingRows, pending.Status);
        Assert.Equal(1, pending.PendingIdentityCount);
        Assert.True(pending.Actions.PrepareRows.Enabled);
        Assert.False(pending.Actions.Convert.Enabled);
        Assert.Contains("pending row", pending.Actions.Convert.DisabledReason!, StringComparison.OrdinalIgnoreCase);

        Apply(service, await service.PlanDataPrepareAsync(new DataPrepareRequest(Location)));
        var prepared = service.Inspect(Location);
        Assert.Equal(ProjectStatus.BytesGenerationRequired, prepared.Status);
        Assert.Equal(0, prepared.PendingIdentityCount);
        Assert.True(prepared.Actions.Convert.Enabled);

        var client = await service.ConvertAsync(new ConvertRequest(Location, "client"));
        var server = await service.ConvertAsync(new ConvertRequest(Location, "server"));
        Assert.True(client.Succeeded, FormatDiagnostics(client));
        Assert.True(server.Succeeded, FormatDiagnostics(server));
        var ready = service.Inspect(Location);
        Assert.Equal(ProjectStatus.Ready, ready.Status);
        Assert.All(ready.GeneratedByteTargets, target =>
            Assert.Equal(ProjectTargetArtifactStatus.Current, target.Status));

        ReplaceBusinessCell(workbookPath, "name", "Changed after convert");
        var staleBytes = service.Inspect(Location);
        Assert.Equal(ProjectStatus.BytesGenerationRequired, staleBytes.Status);
        Assert.Contains("Generate bytes", staleBytes.GeneratedBytes.Status, StringComparison.Ordinal);
        Assert.All(staleBytes.GeneratedByteTargets, target =>
            Assert.Equal(ProjectTargetArtifactStatus.Stale, target.Status));
        Assert.True(staleBytes.Actions.Convert.Enabled);

        File.WriteAllBytes(
            Path.Combine(_root, "Generated", "Bytes", "client", "config.bytes"),
            [1, 2, 3]);
        var corruptBytes = service.Inspect(Location);
        Assert.Equal(ProjectStatus.BytesGenerationRequired, corruptBytes.Status);
        Assert.Equal(
            ProjectTargetArtifactStatus.Corrupt,
            Assert.Single(corruptBytes.GeneratedByteTargets, target => target.Target == "client").Status);
        Assert.Contains(corruptBytes.Diagnostics, diagnostic => diagnostic.Code == "bytes.corrupt");
    }

